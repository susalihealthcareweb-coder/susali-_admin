// Demo data so every dashboard, list and chart has something to show:
// companies, employees, self-registrations waiting for approval, and
// referrals at every stage of the lifecycle spread over recent months,
// each with its status history and sample documents.
// Called from seed.js when SEED_DEMO is on. Adds referrals only once.

const fs = require("fs");
const path = require("path");
const PDFDocument = require("pdfkit");

const H = 3600 * 1000;
const D = 24 * H;

function samplePdf(title, lines) {
  return new Promise((resolve) => {
    const doc = new PDFDocument({ size: "A5", margin: 36 });
    const chunks = [];
    doc.on("data", (c) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.fontSize(16).fillColor("#0f766e").text("SUSALI · sample document");
    doc.moveDown(0.3).fontSize(12).fillColor("#0f172a").text(title);
    doc.moveDown().fontSize(10).fillColor("#334155");
    lines.forEach((l) => doc.text(l));
    doc.moveDown().fontSize(8).fillColor("#94a3b8").text("Demo data generated by prisma/seed-demo.js. Not a real medical record.");
    doc.end();
  });
}

// Writes the file where the app's storage expects it: Cloudflare R2 when
// configured, otherwise local development storage.
let r2;
async function storeFile(key, buf) {
  if (process.env.R2_BUCKET) {
    const { S3Client, PutObjectCommand } = require("@aws-sdk/client-s3");
    r2 ||= new S3Client({
      region: "auto",
      forcePathStyle: true,
      endpoint: process.env.R2_ENDPOINT || `https://${process.env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
      credentials: { accessKeyId: process.env.R2_ACCESS_KEY_ID, secretAccessKey: process.env.R2_SECRET_ACCESS_KEY },
      requestChecksumCalculation: "WHEN_REQUIRED",
      responseChecksumValidation: "WHEN_REQUIRED",
    });
    await r2.send(new PutObjectCommand({ Bucket: process.env.R2_BUCKET, Key: key, Body: buf, ContentType: "application/pdf" }));
    return true;
  }
  const file = path.join(process.cwd(), ".uploads", key);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, buf);
  return true;
}

async function nextNo(prisma, key) {
  const c = await prisma.counter.upsert({ where: { id: key }, create: { id: key, seq: 1 }, update: { seq: { increment: 1 } } });
  return c.seq;
}

